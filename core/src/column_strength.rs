/// 表を引く（配布物の VLOOKUP と同じ完全一致）。見つからなければ None。
pub fn lookup(jas: &str, species: &str, grade: &str) -> Option<f64> {
    TABLE
        .iter()
        .find(|(j, s, g, _)| *j == jas && *s == species && *g == grade)
        .map(|(_, _, _, strength)| *strength)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn looks_up_the_values_of_the_notification_table() {
        assert_eq!(
            lookup("JAS目視等級区分構造用製材", "すぎ", "二級"),
            Some(20.4)
        );
        assert_eq!(lookup("無等級材", "すぎ", "ー"), Some(17.7));
        assert_eq!(
            lookup("JAS同一等級構成集成材", "ー", "E95-F315(4層以上)"),
            Some(26.0)
        );
        assert_eq!(
            lookup("JASA種構造用単板積層材", "ー", "180E　特級"),
            Some(46.8)
        );
        // 配布物の表記のまま（末尾の空白まで含めて一致させる）。
        assert_eq!(
            lookup("JAS機械等級区分構造用製材", "すぎ", "E150 "),
            Some(41.4)
        );
    }

    /// 画面の樹種は「えぞまつ」「とどまつ」に分かれているが、表は
    /// 「えぞまつ及びとどまつ」でひとまとめ。配布物と同じく引き当てられない。
    #[test]
    fn keeps_the_gaps_of_the_distributed_table() {
        assert_eq!(
            lookup("JAS目視等級区分構造用製材", "えぞまつ", "一級"),
            None
        );
        assert_eq!(lookup("JAS機械等級区分構造用製材", "あかまつ", "E50"), None);
        assert_eq!(lookup("", "", ""), None);
    }
}
