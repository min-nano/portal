//! 柱の圧縮の基準強度 Fc（N/mm²）。
//!
//! 平成 12 年建設省告示第 1452 号が定める、樹種・等級ごとの圧縮の基準強度。
//! 表そのものは、必要壁量の表計算ツール（配布物）の隠しシート
//! 「柱の圧縮基準強度」A4:F187 と同じ並び・同じ値で、柱の小径の計算
//! （wall_quantity.rs の 2-2・2-3）が VLOOKUP と同じ引き当てをする。
//!
//! 引き当てのキーは配布物と同じく **JAS 規格 + 樹種等 + 等級等** の連結で、
//! 画面の選択肢（wall_quantity_mapping.json の species / grade）がそのまま
//! 入る。配布物の一覧をそのまま写しているので、次のような癖も残してある:
//!
//!   - 機械等級区分の「E150 」は末尾に空白がある（配布物の表記のまま）。
//!   - 目視等級区分の表は「えぞまつ及びとどまつ」でひとまとめだが、画面の
//!     樹種の選択肢は「えぞまつ」「とどまつ」に分かれている。どちらを選んでも
//!     引き当てられないので、配布物と同じく「該当なし」になる。
//!   - 無等級材・集成材・単板積層材は、樹種または等級の欄が「ー」。
//!
//! この表が配布物とずれていないことは、backend のテスト
//! （test_wall_quantity_calculation.py）が配布物そのものと突き合わせて確かめる。

